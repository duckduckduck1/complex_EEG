import 'package:eeg_app_max30003_stm32/features/annotation/domain/annotation_models.dart';

// readme.txt кладётся в папку эксперимента рядом с данными.
//
// Смысл: данные передают человеку, который приложения не видел. Он должен
// открыть папку и разобраться без нас — что за файлы, как читать сигнал, что
// значат поля и метки. Пишется при старте записи, чтобы лежать на месте даже
// если запись оборвалась.

/// Собирает текст `readme.txt` для папки эксперимента.
String buildExperimentReadme({
  required String experimentName,
  required String experimentId,
  required List<LabelType> labelTypes,
  int sampleRateHz = 250,
}) {
  final states =
      labelTypes
          .where((type) => type.kind == AnnotationKind.state && type.isActive)
          .toList()
        ..sort((a, b) => a.sortOrder.compareTo(b.sortOrder));
  final events =
      labelTypes
          .where((type) => type.kind == AnnotationKind.event && type.isActive)
          .toList()
        ..sort((a, b) => a.sortOrder.compareTo(b.sortOrder));
  final excludes =
      labelTypes
          .where((type) => type.kind == AnnotationKind.exclude && type.isActive)
          .toList()
        ..sort((a, b) => a.sortOrder.compareTo(b.sortOrder));

  String dictionary(List<LabelType> types) =>
      types.map((type) => '  ${type.id} — ${type.displayName}').join('\n');

  return '''
ЭКСПЕРИМЕНТ: $experimentName
Идентификатор записи: $experimentId

Папка собрана приложением оператора ЭЭГ (мышиная лаборатория «Умного сна»).
Ниже — что здесь лежит и как это читать.


ЧТО В ПАПКЕ

  signal.bin       сигнал ПОСЛЕ фильтров — с ним обычно и работают
  signal_raw.bin   тот же сигнал, но как пришёл с устройства, без фильтров
  experiment.json  все метаданные: фильтры, сегменты, разрывы, метки, ФБМ
  journal.ndjson   построчный журнал событий записи (по одному JSON в строке)
  readme.txt       этот файл


КАК ЧИТАТЬ СИГНАЛ

Оба .bin — это подряд идущие отсчёты, без заголовка:

  тип отсчёта      int32, little-endian (4 байта на отсчёт)
  единица          микровольты (мкВ)
  частота          $sampleRateHz Гц
  число отсчётов   размер файла / 4

Файлы одной длины: отсчёт номер N в signal.bin и в signal_raw.bin — один и тот
же момент времени. Время отсчёта = N / $sampleRateHz секунд от начала записи.

Пример на Python:

  import numpy as np
  x = np.fromfile('signal.bin', dtype='<i4')     # мкВ, $sampleRateHz Гц
  raw = np.fromfile('signal_raw.bin', dtype='<i4')
  t = np.arange(x.size) / $sampleRateHz          # секунды

Зачем два файла: фильтр необратим. Если фильтры при записи выбрали неудачно,
перефильтровать можно из signal_raw.bin.


EXPERIMENT.JSON — ЧТО ГДЕ

  experiment_id     машинный идентификатор записи
  display_name      название эксперимента (им же названа эта папка)
  metadata          произвольные пометки оператора
  recording         частота, единицы, кодировка отсчётов, применённые фильтры,
                    уровень ШИМ для ФБМ
  segments          непрерывные куски записи
  gaps              разрывы связи между сегментами
  labels            метки разметки
  fbm_sessions      сеансы света (ФБМ): когда включили, когда погас, сколько горел

Везде, где есть индекс отсчёта, рядом лежит время в чч:мм:сс — индексы нужны
машине, время человеку. Заменять одно другим не нужно, это одно и то же.

СЕГМЕНТЫ И РАЗРЫВЫ. Если связь с устройством обрывалась, запись разбита на
сегменты: start_sample и end_sample — полуоткрытый диапазон [начало, конец).
Отсчётов за время разрыва в файле НЕТ — нулями дырки не заполняются, разрыв
описан в gaps. Поэтому по индексу отсчёта нельзя считать реальное время суток;
для этого есть wall_clock-поля.

МЕТКИ. У метки-интервала есть start_sample/end_sample, у точечной — sample_index.
Метка всегда лежит внутри одного сегмента. Незакрытые метки в файл не попадают.

СЕАНСЫ ФБМ. Один сеанс — одна запись: включили, погасло, duration — сколько
горел. end_reason говорит, почему погас: manual (оператор), auto_off_timer
(истекло заданное время), connection_lost (оборвалась связь), recording_stopped
(остановили запись). Если стоит in_progress, свет ещё горел на момент записи
файла: это снимок, а не итог, и end_time в нём — момент снимка. У connection_lost
смотрите end_command_delivered: false означает, что команда «погасить» до
устройства не доехала и свет физически мог остаться включённым.


СЛОВАРЬ МЕТОК

Состояния (интервалы — что животное делало):
${dictionary(states)}

События (точки — что случилось в конкретный момент):
${dictionary(events)}

Исключения (интервалы — участки, которые лучше не анализировать):
${dictionary(excludes)}

Метки ставит оператор глазами, по поведению животного, а не по сигналу. Метки
артефактов (задели провод, ударилась датчиком, сместился электрод, наводка)
объясняют, откуда на записи скачок амплитуды.


ЕСЛИ ЗАПИСЬ ОБОРВАЛАСЬ

experiment.json пересобирается во время записи примерно раз в полминуты, так
что даже после сбоя питания папка обычно пригодна для разбора — с точностью до
последнего сохранения. Если json оказался старше данных, полную картину можно
восстановить из journal.ndjson: там по порядку записаны старт, границы
сегментов, обрывы, метки и события ФБМ.
''';
}
